static int font_index(char c) {
    if (c >= 'a' && c <= 'z') c = c - 'a' + 'A'; // lowercase -> uppercase
    if (c < 0x20 || c > 'Z')  return 0;           // fallback to space
    return c - 0x20;
}

// =========================================================================
// Ticker buffer  —  circular buffer of captured characters for the banner
// =========================================================================
#define TICKER_MAX 128

typedef struct {
    char  buf[TICKER_MAX];
    int   head;   // index of oldest character
    int   count;  // number of valid characters
} Ticker;

extern Ticker ticker;

static void ticker_init(void) {
    ticker.head  = 0;
    ticker.count = 0;
}

static void ticker_push(char c) {
    int tail = (ticker.head + ticker.count) % TICKER_MAX;
    ticker.buf[tail] = c;
    if (ticker.count < TICKER_MAX)
        ticker.count++;
    else
        ticker.head = (ticker.head + 1) % TICKER_MAX; // overwrite oldest
}

static char ticker_get(int i) {
    return ticker.buf[(ticker.head + i) % TICKER_MAX];
}

// =========================================================================
// Low-level drawing primitives
// =========================================================================
static void fill_rect(int x, int y, int w, int h, uint16_t color) {
    int px, py;
    for (py = y; py < y + h; py++)
        for (px = x; px < x + w; px++)
            if (px >= 0 && px < FB_WIDTH && py >= 0 && py < FB_HEIGHT)
                write_pixel(py * FB_WIDTH + px, color);
}

static void draw_char(char c, int x, int y, int scale, uint16_t fg, uint16_t bg) {
    int idx = font_index(c);
    int row, col;
    for (row = 0; row < FONT_H; row++) {
        uint8_t bits = font8x12[idx][row];
        for (col = 0; col < FONT_W; col++) {
            uint16_t color = (bits & (0x80 >> col)) ? fg : bg;
            fill_rect(x + col * scale, y + row * scale, scale, scale, color);
        }
    }
}

static void draw_string(const char *s, int x, int y, int scale, uint16_t fg, uint16_t bg) {
    int cx = x;
    while (*s) {
        draw_char(*s, cx, y, scale, fg, bg);
        cx += FONT_W * scale + scale;
        s++;
    }
}

// =========================================================================
// VSync blanking wait  —  write pixels only during safe period
// =========================================================================
#define VSYNC_BASE CORE_2_VSYNC_BASE
#define HSYNC_BASE CORE_2_HSYNC_BASE

static void wait_for_blanking(void) {
    while (IORD_ALTERA_AVALON_PIO_DATA(VSYNC_BASE) != 0);
    while (IORD_ALTERA_AVALON_PIO_DATA(VSYNC_BASE) == 0);
}

// =========================================================================
// Scrolling banner  —  top BANNER_H pixels of screen in game mode
// Scrolls the ticker buffer continuously left to right.
// =========================================================================
#define BANNER_H      16
#define BANNER_SCALE  1
#define BANNER_SLOT_W (FONT_W * BANNER_SCALE + 2)
#define BANNER_FG     0xFD0   // warm yellow
#define BANNER_BG     0x112   // dark blue

extern int marquee_pixel_offset;
extern int banner_visible;

static void draw_banner_tick(void) {
	if (screen_busy || !banner_visible) return;

    if (ticker.count == 0) return;

    int total_width = ticker.count * BANNER_SLOT_W;
    int cy          = (BANNER_H - FONT_H * BANNER_SCALE) / 2 + 2;

	marquee_pixel_offset++;
	if (marquee_pixel_offset >= total_width + 4)
		marquee_pixel_offset = -(FB_WIDTH);

    int x;
    for (x = 0; x < FB_WIDTH; x++) {
        int string_x = x + marquee_pixel_offset - 4;

        if (string_x >= 0 && string_x < total_width) {
            int slot   = string_x / BANNER_SLOT_W;
            int char_x = string_x % BANNER_SLOT_W;

            if (slot < ticker.count && char_x < FONT_W * BANNER_SCALE) {
                int mask = (0x80 >> (char_x / BANNER_SCALE));
                int idx  = font_index(ticker_get(slot));
                int addr = cy * FB_WIDTH + x;
                int r;
                for (r = 0; r < FONT_H; r++) {
                    write_pixel(addr, (font8x12[idx][r] & mask) ? BANNER_FG : BANNER_BG);
                    addr += FB_WIDTH;
                }
                continue;
            }
        }

        // Background column
        int addr = cy * FB_WIDTH + x;
        int r;
        for (r = 0; r < FONT_H; r++) {
            write_pixel(addr, BANNER_BG);
            addr += FB_WIDTH;
        }
    }
}

